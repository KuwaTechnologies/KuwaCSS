/** Generates every derived artefact from src/vocab.ts. */
import { PREFIXES, RESPONSIVE, TRANSLATIONS, SPACE, TEXT, type Entry } from '../vocab.ts';

const responsiveSet = new Set<string>(RESPONSIVE);

export function escapeSelector(name: string): string {
  return name.replace(/:/g, '\\:');
}

function decl(css: Record<string, string>): string {
  return Object.entries(css).map(([k, v]) => `${k}:${v}`).join(';');
}

function rule(name: string, css: Record<string, string>): string {
  return `.${escapeSelector(name)}{${decl(css)}}`;
}

/** Variant declarations: primitives drop `gap` so gap-* utilities keep winning at every breakpoint. */
function variantCss(e: Entry): Record<string, string> {
  if (e.kind !== 'primitive') return e.css!;
  const { gap: _gap, ...rest } = e.css!;
  return rest;
}

export function utilitiesCss(list: Entry[]): string {
  const lines: string[] = [];
  for (const e of list) if (e.kind === 'utility') lines.push(rule(e.name, e.css!));
  for (const [prefix, min] of Object.entries(PREFIXES)) {
    lines.push(`@media (min-width: ${min}) {`);
    for (const e of list) if (responsiveSet.has(e.name) && e.css) lines.push(`  ${rule(`${prefix}:${e.name}`, variantCss(e))}`);
    lines.push('}');
  }
  return `@layer kuwa.utilities {\n${lines.join('\n')}\n}\n`;
}

export function primitivesCss(list: Entry[]): string {
  const lines = list.filter((e) => e.kind === 'primitive').map((e) => rule(e.name, e.css!));
  return `@layer kuwa.layout {\n${lines.join('\n')}\n}\n`;
}

export function vocabJson(list: Entry[], version: string): object {
  return {
    $schema: 'https://kuwacss.dev/vocab.schema.json',
    version,
    scales: { space: [...SPACE], text: [...TEXT] },
    prefixes: { ...PREFIXES },
    responsive: [...RESPONSIVE],
    classes: list.map((e) => ({
      name: e.name,
      group: e.group,
      kind: e.kind,
      ...(e.css ? { css: e.css } : {}),
      ...(e.knobs ? { knobs: e.knobs } : {}),
      ...(e.appliesTo ? { appliesTo: e.appliesTo } : {}),
      responsive: responsiveSet.has(e.name),
      description: e.description,
    })),
    translations: { ...TRANSLATIONS },
  };
}

export function allClassNames(list: Entry[]): string[] {
  const names = list.map((e) => e.name);
  for (const prefix of Object.keys(PREFIXES)) for (const r of RESPONSIVE) names.push(`${prefix}:${r}`);
  return names;
}

export function dts(list: Entry[]): string {
  const union = allClassNames(list).map((n) => `  | '${n}'`).join('\n');
  return [
    '// Generated by KuwaCSS from src/vocab.ts. Do not edit.',
    'export type KuwaClass =',
    union + ';',
    '',
    '/** Joins class names with a space, dropping falsy values; each literal is type-checked. */',
    'export function cx(...classes: Array<KuwaClass | false | null | undefined>): string;',
    '',
  ].join('\n');
}
